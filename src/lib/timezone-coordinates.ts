/** Tabloda yoksa boylam = UTC sapması × 15°. Enlem orta kuşak. */
export function coordinatesForTimezone(timeZone: string): [number, number] {
  const known = TIMEZONE_COORDINATES[timeZone];
  if (known) return known;

  const offsetHours = -new Date().getTimezoneOffset() / 60;
  return [41, offsetHours * 15];
}
